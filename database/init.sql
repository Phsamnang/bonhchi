-- 4. Custom Enum Types (Idempotent)
DO $$ BEGIN CREATE TYPE user_role AS ENUM ('owner', 'manager', 'staff'); EXCEPTION WHEN duplicate_object THEN null; END $$;
DO $$ BEGIN CREATE TYPE category_type AS ENUM ('income', 'expense'); EXCEPTION WHEN duplicate_object THEN null; END $$;
DO $$ BEGIN CREATE TYPE wallet_type AS ENUM ('cash', 'bank', 'cash_drawer', 'petty_cash', 'delivery_app', 'staff_advance', 'manager_advance', 'tips'); EXCEPTION WHEN duplicate_object THEN null; END $$;
DO $$ BEGIN CREATE TYPE invoice_type AS ENUM ('expense', 'income'); EXCEPTION WHEN duplicate_object THEN null; END $$;
DO $$ BEGIN CREATE TYPE expense_kind AS ENUM ('product', 'small'); EXCEPTION WHEN duplicate_object THEN null; END $$;
DO $$ BEGIN CREATE TYPE invoice_status AS ENUM ('paid', 'partial', 'unpaid', 'void'); EXCEPTION WHEN duplicate_object THEN null; END $$;
DO $$ BEGIN CREATE TYPE payment_method AS ENUM ('cash', 'qr', 'bank_transfer', 'credit'); EXCEPTION WHEN duplicate_object THEN null; END $$;
DO $$ BEGIN CREATE TYPE request_status AS ENUM ('pending', 'approved', 'rejected', 'settled'); EXCEPTION WHEN duplicate_object THEN null; END $$;

-- 5. Helper functions for PostgREST JWT claims
DROP FUNCTION IF EXISTS current_user_id() CASCADE;
DROP FUNCTION IF EXISTS request_jwt_claim(TEXT) CASCADE;
DROP FUNCTION IF EXISTS current_user_role() CASCADE;

CREATE OR REPLACE FUNCTION request_jwt_claim(claim TEXT) RETURNS TEXT AS $$
    SELECT NULLIF(current_setting('request.jwt.claims', true)::jsonb ->> claim, '');
$$ LANGUAGE SQL STABLE;

CREATE OR REPLACE FUNCTION current_user_id() RETURNS BIGINT AS $$
    SELECT NULLIF(current_setting('request.jwt.claims', true)::jsonb ->> 'sub', '')::BIGINT;
$$ LANGUAGE SQL STABLE;

CREATE OR REPLACE FUNCTION current_user_role() RETURNS TEXT AS $$
    SELECT NULLIF(current_setting('request.jwt.claims', true)::jsonb ->> 'role', '');
$$ LANGUAGE SQL STABLE;

-- 6. Tables Definition (All Primary Keys use BIGINT)
DROP TABLE IF EXISTS audit_log CASCADE;
DROP TABLE IF EXISTS request_distributions CASCADE;
DROP TABLE IF EXISTS money_requests CASCADE;
DROP TABLE IF EXISTS wallet_counts CASCADE;
DROP TABLE IF EXISTS transfers CASCADE;
DROP TABLE IF EXISTS invoice_payments CASCADE;
DROP TABLE IF EXISTS invoice_items CASCADE;
DROP TABLE IF EXISTS invoices CASCADE;
DROP TABLE IF EXISTS products CASCADE;
DROP TABLE IF EXISTS suppliers CASCADE;
DROP TABLE IF EXISTS categories CASCADE;
DROP TABLE IF EXISTS wallets CASCADE;
DROP TABLE IF EXISTS users CASCADE;

CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(100) UNIQUE NOT NULL,
    name VARCHAR(100) NOT NULL,
    phone VARCHAR(20),
    password_hash VARCHAR(255) NOT NULL,
    avatar_url TEXT,
    role user_role NOT NULL DEFAULT 'staff',
    is_active BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name_km VARCHAR(100) NOT NULL,
    name_en VARCHAR(100),
    type category_type NOT NULL,
    parent_id BIGINT REFERENCES categories(id) ON DELETE SET NULL,
    icon VARCHAR(50),
    is_active BOOLEAN NOT NULL DEFAULT true
);

CREATE TABLE IF NOT EXISTS suppliers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    market_location VARCHAR(100),
    contact_phone VARCHAR(50),
    note TEXT,
    is_active BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    default_unit VARCHAR(50) NOT NULL,
    category_id BIGINT REFERENCES categories(id) ON DELETE RESTRICT,
    supplier_id BIGINT REFERENCES suppliers(id) ON DELETE SET NULL,
    default_currency VARCHAR(3) CHECK (default_currency IN ('USD', 'KHR')),
    default_unit_price DECIMAL(14,2) DEFAULT 0,
    is_active BOOLEAN NOT NULL DEFAULT true
);

CREATE TABLE IF NOT EXISTS wallets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(50) UNIQUE NOT NULL,
    name_km VARCHAR(100) NOT NULL,
    name_en VARCHAR(100) NOT NULL,
    type wallet_type NOT NULL,
    category VARCHAR(20) NOT NULL DEFAULT 'cash' CHECK (category IN ('cash', 'bank', 'advance', 'other')),
    opening_usd DECIMAL(12,2) NOT NULL DEFAULT 0.00,
    opening_khr DECIMAL(14,0) NOT NULL DEFAULT 0,
    current_usd DECIMAL(12,2) NOT NULL DEFAULT 0.00,
    current_khr DECIMAL(14,0) NOT NULL DEFAULT 0,
    is_active BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS invoices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_no VARCHAR(50) UNIQUE NOT NULL,
    invoice_date DATE NOT NULL DEFAULT CURRENT_DATE,
    invoice_time TIME NOT NULL DEFAULT CURRENT_TIME,
    type invoice_type NOT NULL DEFAULT 'expense',
    expense_kind expense_kind,
    market_trip_id BIGINT,
    supplier_id BIGINT REFERENCES suppliers(id) ON DELETE RESTRICT,
    supplier_name VARCHAR(150),
    category_id BIGINT REFERENCES categories(id) ON DELETE RESTRICT,
    category_name VARCHAR(100),
    wallet_code VARCHAR(50),
    total_usd DECIMAL(12,2) NOT NULL DEFAULT 0.00,
    total_khr DECIMAL(14,0) NOT NULL DEFAULT 0,
    paid_usd DECIMAL(12,2) NOT NULL DEFAULT 0.00,
    paid_khr DECIMAL(14,0) NOT NULL DEFAULT 0,
    status invoice_status NOT NULL DEFAULT 'paid',
    void_reason VARCHAR(100),
    voided_by BIGINT REFERENCES users(id),
    voided_at TIMESTAMPTZ,
    receipt_url TEXT,
    note TEXT,
    created_by BIGINT REFERENCES users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS invoice_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id BIGINT NOT NULL REFERENCES invoices(id) ON DELETE CASCADE,
    product_id BIGINT REFERENCES products(id) ON DELETE RESTRICT,
    item_name VARCHAR(150) NOT NULL,
    quantity DECIMAL(10,3) NOT NULL CHECK (quantity > 0),
    unit VARCHAR(50) NOT NULL,
    unit_price DECIMAL(14,2) NOT NULL CHECK (unit_price >= 0),
    currency VARCHAR(3) NOT NULL CHECK (currency IN ('USD', 'KHR')),
    line_total DECIMAL(14,2) NOT NULL CHECK (line_total >= 0),
    is_paid BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS invoice_payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id BIGINT NOT NULL REFERENCES invoices(id) ON DELETE CASCADE,
    wallet_id BIGINT NOT NULL REFERENCES wallets(id) ON DELETE RESTRICT,
    amount DECIMAL(14,2) NOT NULL CHECK (amount > 0),
    currency VARCHAR(3) NOT NULL CHECK (currency IN ('USD', 'KHR')),
    method payment_method NOT NULL DEFAULT 'cash',
    cross_currency_rate DECIMAL(10,4),
    paid_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    created_by BIGINT REFERENCES users(id)
);

CREATE TABLE IF NOT EXISTS transfers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transfer_date DATE NOT NULL DEFAULT CURRENT_DATE,
    from_wallet_id BIGINT NOT NULL REFERENCES wallets(id) ON DELETE RESTRICT,
    to_wallet_id BIGINT NOT NULL REFERENCES wallets(id) ON DELETE RESTRICT,
    amount DECIMAL(14,2) NOT NULL CHECK (amount > 0),
    currency VARCHAR(3) NOT NULL CHECK (currency IN ('USD', 'KHR')),
    note TEXT,
    request_id BIGINT,
    created_by BIGINT REFERENCES users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS wallet_counts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    wallet_id BIGINT NOT NULL REFERENCES wallets(id) ON DELETE RESTRICT,
    currency VARCHAR(3) NOT NULL CHECK (currency IN ('USD', 'KHR')),
    count_date DATE NOT NULL DEFAULT CURRENT_DATE,
    system_amount DECIMAL(14,2) NOT NULL,
    counted_amount DECIMAL(14,2) NOT NULL,
    difference DECIMAL(14,2) GENERATED ALWAYS AS (counted_amount - system_amount) STORED,
    tolerance_threshold DECIMAL(14,2) NOT NULL,
    denominations_breakdown JSONB NOT NULL,
    reason_for_gap TEXT,
    is_blind_count BOOLEAN NOT NULL DEFAULT true,
    counted_by BIGINT REFERENCES users(id),
    verified_by BIGINT REFERENCES users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS money_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    requested_by BIGINT NOT NULL REFERENCES users(id),
    amount DECIMAL(14,2) NOT NULL CHECK (amount > 0),
    currency VARCHAR(3) NOT NULL CHECK (currency IN ('USD', 'KHR')),
    category_id BIGINT REFERENCES categories(id) ON DELETE RESTRICT,
    reason TEXT NOT NULL,
    status request_status NOT NULL DEFAULT 'pending',
    approved_by BIGINT REFERENCES users(id),
    approved_at TIMESTAMPTZ,
    rejection_reason TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS request_distributions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id BIGINT NOT NULL REFERENCES money_requests(id) ON DELETE CASCADE,
    recipient_name VARCHAR(100) NOT NULL,
    amount DECIMAL(14,2) NOT NULL CHECK (amount > 0),
    currency VARCHAR(3) NOT NULL CHECK (currency IN ('USD', 'KHR')),
    given_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    note TEXT
);

CREATE TABLE IF NOT EXISTS audit_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    table_name VARCHAR(50) NOT NULL,
    record_id BIGINT NOT NULL,
    action VARCHAR(20) NOT NULL,
    old_value JSONB,
    new_value JSONB,
    user_id BIGINT REFERENCES users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Sequence privileges for PostgREST & Authenticated Roles
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO anon, authenticated, bonchi_owner, bonchi_manager, bonchi_staff;

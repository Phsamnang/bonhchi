-- 7. Row Level Security (RLS) Configuration for PostgREST & PostgreSQL
ALTER TABLE wallets ENABLE ROW LEVEL SECURITY;
ALTER TABLE invoices ENABLE ROW LEVEL SECURITY;
ALTER TABLE wallet_counts ENABLE ROW LEVEL SECURITY;

-- Wallet RLS Policies:
-- Owners see all wallets
DROP POLICY IF EXISTS wallets_owner_all ON wallets;
CREATE POLICY wallets_owner_all ON wallets
    FOR ALL TO bonchi_owner USING (true);

-- Managers see Cash Drawer & Petty Cash
DROP POLICY IF EXISTS wallets_manager_select ON wallets;
CREATE POLICY wallets_manager_select ON wallets
    FOR SELECT TO bonchi_manager
    USING (code IN ('drawer', 'petty', 'mgr', 'aba', 'bakong'));

-- Staff only see Petty Cash
DROP POLICY IF EXISTS wallets_staff_select ON wallets;
CREATE POLICY wallets_staff_select ON wallets
    FOR SELECT TO bonchi_staff
    USING (code IN ('petty'));

-- Invoices RLS Policies:
DROP POLICY IF EXISTS invoices_owner_all ON invoices;
CREATE POLICY invoices_owner_all ON invoices
    FOR ALL TO bonchi_owner USING (true);

DROP POLICY IF EXISTS invoices_manager_select_insert ON invoices;
CREATE POLICY invoices_manager_select_insert ON invoices
    FOR ALL TO bonchi_manager USING (true);

DROP POLICY IF EXISTS invoices_staff_insert ON invoices;
CREATE POLICY invoices_staff_insert ON invoices
    FOR INSERT TO bonchi_staff WITH CHECK (true);

DROP POLICY IF EXISTS invoices_staff_select ON invoices;
CREATE POLICY invoices_staff_select ON invoices
    FOR SELECT TO bonchi_staff USING (created_by = current_user_id() OR invoice_date = CURRENT_DATE);


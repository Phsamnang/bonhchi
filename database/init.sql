-- 1. Create PostgREST User Roles
DO $$
BEGIN
    IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'anon') THEN
        CREATE ROLE anon NOLOGIN;
    END IF;
    IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'authenticated') THEN
        CREATE ROLE authenticated NOLOGIN;
    END IF;
    IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'bonchi_owner') THEN
        CREATE ROLE bonchi_owner NOLOGIN IN ROLE authenticated;
    END IF;
    IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'bonchi_manager') THEN
        CREATE ROLE bonchi_manager NOLOGIN IN ROLE authenticated;
    END IF;
    IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'bonchi_staff') THEN
        CREATE ROLE bonchi_staff NOLOGIN IN ROLE authenticated;
    END IF;
    IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'authenticator') THEN
        CREATE ROLE authenticator NOINHERIT LOGIN PASSWORD 'bonchi_authenticator_secret_2026';
    END IF;
END $$;

GRANT anon TO authenticator;
GRANT authenticated TO authenticator;
GRANT bonchi_owner TO authenticator;
GRANT bonchi_manager TO authenticator;
GRANT bonchi_staff TO authenticator;


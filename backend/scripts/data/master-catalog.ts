/**
 * Supplier → product catalog used by scripts/seed-master-data.ts.
 * [name, unit, default price, currency]. Each product name belongs to exactly one supplier —
 * the seed script refuses duplicates across suppliers.
 */
export type Cur = 'USD' | 'KHR';
export type CatalogItem = [name: string, unit: string, price: number, currency: Cur];
export type CategoryName = 'Ingredients' | 'Ice' | 'Gas';
export type SupplierCatalog = {
  name: string;
  location: string | null;
  /** Matched against categories.name_en; left empty if the database has no such category */
  category: CategoryName;
  items: CatalogItem[];
};

/** Build "<base> <variant>" items, e.g. beer brand × can/bottle */
const combos = (
  bases: Array<[string, number]>,
  variants: Array<[string, number]>,
  unit: string,
  currency: Cur
): CatalogItem[] =>
  bases.flatMap(([b, price]) => variants.map(([v, f]) => [`${b} ${v}`.trim(), unit, Math.round(price * f * 100) / 100, currency] as CatalogItem));

const kg = (names: Array<[string, number]>): CatalogItem[] => names.map(([n, p]) => [n, 'គីឡូ', p, 'KHR']);

